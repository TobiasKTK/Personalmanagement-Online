CREATE TABLE selfservice_kontakt (
    mitarbeiter_id BIGINT PRIMARY KEY REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    telefon VARCHAR(80) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL DEFAULT '',
    version BIGINT NOT NULL DEFAULT 0 CHECK(version >= 0)
);
CREATE TABLE selfservice_antrag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mitarbeiter_id BIGINT NOT NULL REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    antragsteller VARCHAR(80) NOT NULL,
    art VARCHAR(20) NOT NULL CHECK(art IN ('KONTAKT', 'BANK')),
    vorher CLOB NOT NULL,
    nachher CLOB NOT NULL,
    bestandsversion BIGINT NOT NULL CHECK(bestandsversion >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'BEANTRAGT' CHECK(status IN ('BEANTRAGT', 'GENEHMIGT', 'ABGELEHNT')),
    grund VARCHAR(500) NOT NULL DEFAULT '',
    erstellt TIMESTAMP WITH TIME ZONE NOT NULL,
    entschieden TIMESTAMP WITH TIME ZONE,
    bearbeiter VARCHAR(80),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version >= 0)
);
CREATE INDEX selfservice_antrag_person ON selfservice_antrag(mitarbeiter_id, status, id);
