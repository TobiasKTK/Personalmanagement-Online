CREATE TABLE personalprozess_vorlage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    typ VARCHAR(20) NOT NULL CHECK (typ IN ('ONBOARDING', 'OFFBOARDING')),
    titel VARCHAR(160) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE TABLE personalprozess_vorlagenaufgabe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorlage_id BIGINT NOT NULL REFERENCES personalprozess_vorlage(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    titel VARCHAR(160) NOT NULL,
    tage INTEGER NOT NULL CHECK (tage BETWEEN -365 AND 365),
    UNIQUE (vorlage_id, position)
);
CREATE TABLE personalprozess_vorgang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mitarbeiter_id BIGINT NOT NULL REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    typ VARCHAR(20) NOT NULL CHECK (typ IN ('ONBOARDING', 'OFFBOARDING')),
    titel VARCHAR(160) NOT NULL,
    bezugsdatum DATE NOT NULL,
    erstellt_von VARCHAR(100) NOT NULL,
    erstellt TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE personalprozess_aufgabe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorgang_id BIGINT NOT NULL REFERENCES personalprozess_vorgang(id) ON DELETE CASCADE,
    titel VARCHAR(160) NOT NULL,
    verantwortlich VARCHAR(100) NOT NULL,
    faellig_am DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OFFEN' CHECK (status IN ('OFFEN', 'IN_BEARBEITUNG', 'ERLEDIGT')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE INDEX personalprozess_aufgabe_zustaendig ON personalprozess_aufgabe(verantwortlich, faellig_am);
CREATE INDEX personalprozess_aufgabe_vorgang ON personalprozess_aufgabe(vorgang_id);
