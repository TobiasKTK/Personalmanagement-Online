CREATE TABLE personaldaten (
    mitarbeiter_id BIGINT PRIMARY KEY REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    profil_id BIGINT REFERENCES stellenprofil(id),
    daten CLOB NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE TABLE beschaeftigungszeit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mitarbeiter_id BIGINT NOT NULL REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    beginn DATE NOT NULL,
    ende DATE NOT NULL,
    austrittsgrund VARCHAR(240) NOT NULL DEFAULT '',
    kuendigungsdatum DATE,
    CHECK (ende >= beginn),
    CHECK (kuendigungsdatum IS NULL OR kuendigungsdatum <= ende)
);
CREATE INDEX beschaeftigungszeit_person ON beschaeftigungszeit(mitarbeiter_id, beginn);
CREATE TABLE personaldaten_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mitarbeiter_id BIGINT NOT NULL REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    zeitpunkt TIMESTAMP WITH TIME ZONE NOT NULL,
    bearbeiter VARCHAR(80) NOT NULL,
    stand CLOB NOT NULL
);
CREATE INDEX personaldaten_revision_person ON personaldaten_revision(mitarbeiter_id, id);
CREATE TABLE personaldokument (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mitarbeiter_id BIGINT NOT NULL REFERENCES mitarbeiter(id) ON DELETE CASCADE,
    titel VARCHAR(160) NOT NULL,
    art VARCHAR(40) NOT NULL,
    quelle VARCHAR(40) NOT NULL,
    monat VARCHAR(7) NOT NULL,
    dateiname VARCHAR(160) NOT NULL,
    groesse BIGINT NOT NULL CHECK (groesse > 0 AND groesse <= 5242880),
    inhalt BLOB NOT NULL,
    erstellt_am TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX personaldokument_person ON personaldokument(mitarbeiter_id, monat, id);
