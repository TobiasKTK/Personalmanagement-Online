CREATE TABLE mandantenspeicher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    name_normalisiert VARCHAR(240) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('VORBEREITUNG', 'AKTIV')),
    version BIGINT NOT NULL DEFAULT 0
);
