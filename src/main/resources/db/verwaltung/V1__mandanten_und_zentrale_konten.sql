CREATE TABLE konto (
    username VARCHAR(80) PRIMARY KEY,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL,
    systemverwaltung BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE konto_mandant (
    username VARCHAR(80) NOT NULL REFERENCES konto(username),
    mandantenspeicher_id BIGINT NOT NULL REFERENCES mandantenspeicher(id),
    PRIMARY KEY (username, mandantenspeicher_id)
);
